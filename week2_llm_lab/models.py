
from typing import Literal

from pydantic import BaseModel, ConfigDict


class Intent(BaseModel):
    """
    Defines the expected structure of an intent
    generated by the LLM.
    """

    # Reject fields that are not defined in this model.
    model_config = ConfigDict(extra="forbid")

    # Contract version
    schema_version: Literal["1.0"]

    # Allowed intent values
    intent_type: Literal["draft_requirement", "unsupported"]

    # Allowed requirement categories
    requirement_type: Literal[
        "functional",
        "non_functional",
        "unspecified"
    ]

    # Required field, but its value can be null.
    requirement_text: str | None

    # Indicates whether clarification is needed.
    clarification_needed: bool

    # Required field, but its value can be null.
    clarification_question: str | None
